/** Las tres pronunciaciones del verbo, por ejemplo ["kʌt", "kʌt", "kʌt"]. */
export function ipa(base: string): [string, string, string] | null {
  const row = table[base];
  if (!row) return null;
  const forms = row.split("|").map((item) => item.trim());
  for (let i = 1; i < forms.length; i++) if (forms[i] === "=") forms[i] = forms[i - 1];
  return forms as [string, string, string];
}

const slashes = (value: string) => value.split(",").map((item) => `/${item.trim()}/`).join(", ");

/** Una forma lista para mostrar: "/brɔt/" o "/bɝnt/, /bɝnd/". */
export function ipaLabel(value: string) {
  return slashes(value);
}

